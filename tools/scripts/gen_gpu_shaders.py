#!/usr/bin/env python3
"""Compile nmo_render's fixed function shaders and embed them in C headers.

The fixed function shader (src/render/gpu/shaders/fixed.vert, fixed.frag)
is built twice, smooth and flat shaded, to SPIR-V with glslc, and from that
to Metal Shading Language source with spirv-cross and to DXIL through
spirv-cross's HLSL and dxc, for the SDL_GPU backend:
src/render/gpu/shaders/fixed_shaders.h. The shader's resource sets are the
register spaces SDL_GPU's Direct3D 12 backend binds, and its vertex inputs
TEXCOORD<location>, as SDL wants them. dxc signs the DXIL with its own
validator, which Direct3D 12 needs to load it. The smooth one is also turned into
GLSL 3.30 and GLSL ES 3.00 (WebGL 2), its clip space depth made OpenGL's,
for the GL3 backend: src/render/gl3/shaders/fixed_glsl.h. Both headers are
checked in, so building the backends needs none of these tools; run this
after changing a shader.

    python3 tools/scripts/gen_gpu_shaders.py [--check]

--check regenerates in memory and fails when the checked-in header differs.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SHADERS = ROOT / "src" / "render" / "gpu" / "shaders"
HEADER = SHADERS / "fixed_shaders.h"
GLSL_HEADER = ROOT / "src" / "render" / "gl3" / "shaders" / "fixed_glsl.h"
# The GLSL dialects of the GL3 backend: (name, spirv-cross options)
GLSL_DIALECTS = (("core", ["--no-es", "--version", "330", "--no-420pack-extension"]),
                 ("es", ["--es", "--version", "300"]))
STAGES = (("vert", "vertex"), ("frag", "fragment"))
VARIANTS = (("smooth", []), ("flat", ["-DFLAT"]))


def tool(name: str) -> str:
    path = shutil.which(name)
    if path is None:
        sys.exit(f"error: {name} is not on PATH")
    return path


def c_bytes(name: str, data: bytes) -> str:
    lines = [f"static const unsigned char {name}[{len(data)}] = {{"]
    for start in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02x}" for b in data[start:start + 16])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def generate_glsl() -> str:
    """The shader, smooth and flat shaded, as GLSL 3.30 and GLSL ES 3.00 source, Z clip space
    made [-w, w]."""
    glslc, spirv_cross = tool("glslc"), tool("spirv-cross")
    parts = [
        "/* Generated by tools/scripts/gen_gpu_shaders.py from ../../gpu/shaders/fixed.vert and"
        " fixed.frag: do not edit. */",
        "",
        "#ifndef NMO_RENDER_GL3_FIXED_GLSL_H",
        "#define NMO_RENDER_GL3_FIXED_GLSL_H",
        "",
    ]
    with tempfile.TemporaryDirectory() as temp:
        for variant, defines in VARIANTS:
            for ext, stage in STAGES:
                spv = Path(temp) / f"{variant}.{ext}.spv"
                subprocess.run([glslc, f"-fshader-stage={ext}", "--target-env=vulkan1.0",
                                *defines, str(SHADERS / f"fixed.{ext}"), "-o", str(spv)], check=True)
                for dialect, options in GLSL_DIALECTS:
                    fixup = ["--fixup-clipspace"] if ext == "vert" else []
                    glsl = subprocess.run([spirv_cross, str(spv), *options, *fixup], check=True,
                                          capture_output=True, text=True).stdout
                    # A NUL byte at the end: render_gl3.c treats these as C strings (strlen),
                    # unlike the SPIR-V/MSL ones above, which it takes by their exact byte size.
                    parts.append(c_bytes(f"fixed_{dialect}_{variant}_{stage}_glsl",
                                         glsl.encode("utf-8") + b"\0"))
                    parts.append("")
    parts.append("#endif /* NMO_RENDER_GL3_FIXED_GLSL_H */")
    return "\n".join(parts) + "\n"


def generate() -> str:
    glslc, spirv_cross, dxc = tool("glslc"), tool("spirv-cross"), tool("dxc")
    parts = [
        "/* Generated by tools/scripts/gen_gpu_shaders.py from fixed.vert and fixed.frag: do not edit. */",
        "",
        "#ifndef NMO_RENDER_GPU_FIXED_SHADERS_H",
        "#define NMO_RENDER_GPU_FIXED_SHADERS_H",
        "",
    ]
    with tempfile.TemporaryDirectory() as temp:
        for variant, defines in VARIANTS:
            for ext, stage in STAGES:
                spv = Path(temp) / f"{variant}.{ext}.spv"
                subprocess.run([glslc, f"-fshader-stage={ext}", "--target-env=vulkan1.0", "-O",
                                *defines, str(SHADERS / f"fixed.{ext}"), "-o", str(spv)], check=True)
                msl = subprocess.run([spirv_cross, str(spv), "--msl", "--msl-version", "20000",
                                      "--msl-decoration-binding"], check=True, capture_output=True,
                                     text=True).stdout
                hlsl = Path(temp) / f"{variant}.{ext}.hlsl"
                hlsl.write_text(subprocess.run([spirv_cross, str(spv), "--hlsl", "--shader-model", "60"],
                                               check=True, capture_output=True, text=True).stdout)
                dxil = Path(temp) / f"{variant}.{ext}.dxil"
                profile = "vs_6_0" if ext == "vert" else "ps_6_0"
                subprocess.run([dxc, "-T", profile, "-E", "main", "-Qstrip_debug", "-Qstrip_reflect",
                                str(hlsl), "-Fo", str(dxil)], check=True)
                name = f"fixed_{variant}_{stage}"
                parts.append(c_bytes(f"{name}_spirv", spv.read_bytes()))
                parts.append("")
                parts.append(c_bytes(f"{name}_msl", msl.encode("utf-8")))
                parts.append("")
                parts.append(c_bytes(f"{name}_dxil", dxil.read_bytes()))
                parts.append("")
    parts.append("#endif /* NMO_RENDER_GPU_FIXED_SHADERS_H */")
    return "\n".join(parts) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the header is out of date")
    args = parser.parse_args()
    outputs = ((HEADER, generate()), (GLSL_HEADER, generate_glsl()))
    if args.check:
        stale = [header for header, text in outputs
                 if not header.exists() or header.read_text() != text]
        for header in stale:
            print(f"{header.relative_to(ROOT)} is out of date: run {Path(__file__).name}")
        return 1 if stale else 0
    for header, text in outputs:
        header.parent.mkdir(parents=True, exist_ok=True)
        header.write_text(text)
        print(f"wrote {header.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
