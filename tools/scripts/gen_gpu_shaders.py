#!/usr/bin/env python3
"""Compile nmo_render's SDL_GPU shaders and embed them in a C header.

The fixed function shader (src/render/gpu/shaders/fixed.vert, fixed.frag)
is built twice, smooth and flat shaded, to SPIR-V with glslc and from that
to Metal Shading Language source with spirv-cross. The results go into
src/render/gpu/shaders/fixed_shaders.h, which is checked in, so building
the backend needs none of these tools; run this after changing a shader.

    python3 tools/scripts/gen_gpu_shaders.py [--check]

--check regenerates in memory and fails when the checked-in header differs.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SHADERS = ROOT / "src" / "render" / "gpu" / "shaders"
HEADER = SHADERS / "fixed_shaders.h"
STAGES = (("vert", "vertex"), ("frag", "fragment"))
VARIANTS = (("smooth", []), ("flat", ["-DFLAT"]))


def tool(name: str) -> str:
    path = shutil.which(name)
    if path is None:
        sys.exit(f"error: {name} is not on PATH")
    return path


def c_bytes(name: str, data: bytes) -> str:
    lines = [f"static const unsigned char {name}[{len(data)}] = {{"]
    for start in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02x}" for b in data[start:start + 16])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def generate() -> str:
    glslc, spirv_cross = tool("glslc"), tool("spirv-cross")
    parts = [
        "/* Generated by tools/scripts/gen_gpu_shaders.py from fixed.vert and fixed.frag: do not edit. */",
        "",
        "#ifndef NMO_RENDER_GPU_FIXED_SHADERS_H",
        "#define NMO_RENDER_GPU_FIXED_SHADERS_H",
        "",
    ]
    with tempfile.TemporaryDirectory() as temp:
        for variant, defines in VARIANTS:
            for ext, stage in STAGES:
                spv = Path(temp) / f"{variant}.{ext}.spv"
                subprocess.run([glslc, f"-fshader-stage={ext}", "--target-env=vulkan1.0", "-O",
                                *defines, str(SHADERS / f"fixed.{ext}"), "-o", str(spv)], check=True)
                msl = subprocess.run([spirv_cross, str(spv), "--msl", "--msl-version", "20000",
                                      "--msl-decoration-binding"], check=True, capture_output=True,
                                     text=True).stdout
                name = f"fixed_{variant}_{stage}"
                parts.append(c_bytes(f"{name}_spirv", spv.read_bytes()))
                parts.append("")
                parts.append(c_bytes(f"{name}_msl", msl.encode("utf-8")))
                parts.append("")
    parts.append("#endif /* NMO_RENDER_GPU_FIXED_SHADERS_H */")
    return "\n".join(parts) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the header is out of date")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not HEADER.exists() or HEADER.read_text() != text:
            print(f"{HEADER.relative_to(ROOT)} is out of date: run {Path(__file__).name}")
            return 1
        return 0
    HEADER.write_text(text)
    print(f"wrote {HEADER.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
