/* `count` samples (a power of two up to 1024) windowed into real parts, the imaginary ones zero */
static bool spectrum_load(const int8_t *samples, uint32_t count, int32_t *re, int32_t *im)
{
    uint32_t size = 1024;
    while (size != count) {
        size >>= 1;
        if (size == 0) {
            return false;
        }
    }
    const uint32_t step = 0x400u / count;
    uint32_t w = step / 2u;
    for (uint32_t i = 0; i < count; i++, w += step) {
        re[i] = (spectrum_window[w] * samples[i]) >> 8;
        im[i] = 0;
    }
    return true;
}

/* In place, halving at each stage; the twiddles from the sine table (index << (9 - stage)) */
static void spectrum_transform(int32_t *re, int32_t *im, uint32_t n)
{
    for (uint32_t i = 1, j = 0; i <= n - 1u; i++) {
        uint32_t bit = n;
        do {
            bit >>= 1;
        } while (bit + j > n - 1u);
        j = bit + (j & (bit - 1u));
        if (j > i) {
            int32_t t = re[i];
            re[i] = re[j];
            re[j] = t;
            t = im[i];
            im[i] = im[j];
            im[j] = t;
        }
    }
    int shift = 9;
    for (uint32_t half = 1; half < n; half *= 2u, shift--) {
        for (uint32_t k = 0; k < half; k++) {
            const int32_t c = spectrum_sine[(k << shift) + 256u];
            const int32_t s = -spectrum_sine[k << shift];
            for (uint32_t a = k; a < n; a += 2u * half) {
                const uint32_t b = a + half;
                const int32_t t_im = (int32_t)((uint32_t)c * (uint32_t)im[b] + (uint32_t)s * (uint32_t)re[b]) >> 16;
                const int32_t t_re = (int32_t)((uint32_t)c * (uint32_t)re[b] - (uint32_t)s * (uint32_t)im[b]) >> 16;
                const int32_t a_re = re[a] >> 1, a_im = im[a] >> 1;
                re[b] = a_re - t_re;
                im[b] = a_im - t_im;
                re[a] = t_re + a_re;
                im[a] = t_im + a_im;
            }
        }
    }
}

/* The levels of the first half's bins (bin 0 left at 0), stretched over `bands` */
static void spectrum_bands(const int32_t *re, const int32_t *im, uint32_t n, uint8_t *out,
                           uint32_t bands)
{
    const uint32_t half = n / 2u;
    if (bands < half) {
        return;
    }
    /* Room past the half: the line reads one level ahead of the last */
    uint8_t *levels = (uint8_t *)calloc(half + 2u + bands, 1u);
    if (levels == NULL) {
        return;
    }
    for (uint32_t k = 1; k < half; k++) {
        const int32_t power = (int32_t)((uint32_t)im[k] * (uint32_t)im[k] + (uint32_t)re[k] * (uint32_t)re[k]) >> 3;
        int32_t level = 127;
        for (int32_t step = 64; step != 0; step >>= 1) {
            level += spectrum_levels[level] < power ? step : -step;
        }
        levels[k] = (uint8_t)level;
    }
    if (half == bands) {
        memcpy(out, levels, half);
        free(levels);
        return;
    }
    /* sub_247C2430: a line drawn from one level to the next across the bands */
    int32_t error = 2 * (int32_t)half - (int32_t)bands, written = 0, at = 0;
    const uint8_t *from = levels;
    for (;;) {
        if (error < 0) {
            error += 2 * (int32_t)half;
        } else {
            const int32_t span = at - written;
            error += 2 * ((int32_t)half - (int32_t)bands);
            for (int32_t i = 0; i < span; i++) {
                out[written + i] = (uint8_t)((i * from[1] + (span - i) * from[0]) / span);
            }
            written = at;
            from++;
        }
        at++;
        if (at >= (int32_t)bands) {
            break;
        }
    }
    for (; written < (int32_t)bands; written++) {
        out[written] = written > 0 ? out[written - 1] : out[written];
    }
    free(levels);
}

/* One channel's samples through the FFT into `bands` levels; false when the count is no power of two */
static bool spectrum_channel(const int8_t *samples, uint32_t count, uint8_t *out, uint32_t bands)
{
    int32_t *re = (int32_t *)calloc(count > 0 ? count : 1u, sizeof(int32_t));
    int32_t *im = (int32_t *)calloc(count > 0 ? count : 1u, sizeof(int32_t));
    bool ok = re != NULL && im != NULL && count > 0 && spectrum_load(samples, count, re, im);
    if (ok) {
        spectrum_transform(re, im, count);
        spectrum_bands(re, im, count, out, bands);
    }
    free(re);
    free(im);
    return ok;
}

/* The plugin's byte for a sample: an 8-bit one plus 127, a 16-bit one (unsigned) over 255 */
static int8_t spectrum_sample(const uint8_t *at, uint16_t bits)
{
    if (bits == 8) {
        return (int8_t)(uint8_t)(at[0] + 127u);
    }
    const uint16_t value = (uint16_t)(at[0] | at[1] << 8);
    return (int8_t)(uint8_t)(value / 255u);
}

/* ---- The block ---- */

enum { SPECTRUM_BAND_COUNT = 0, SPECTRUM_TICK = 1, SPECTRUM_BANDS = 2 };

/*
 * Get Sound Spectrum: once a frame (its Tick local), the Band Count samples
 * a channel from the target sound's play position (wrapping to its start)
 * go through the FFT into Band Count levels (two channels averaged); then
 * Value is the mean level over the bands from Start to End Frequency, a
 * band being half the sample rate over Band Count. Nothing without a
 * target, or when Start is not below End.
 */
static int bb_get_sound_spectrum(blk_t *b)
{
    IN_OFF(b, 0);
    OUT_ON(b, 0);
    nmo_object_id_t target = nmo_engine_block_target(b);
    eng_sound_t *sound = target != 0 ? eng_sound(b->engine, target) : NULL;
    if (sound == NULL) {
        return NMO_ENGINE_BR_OK;
    }
    int32_t bands = 128;
    nmo_engine_block_get_local_value(b, SPECTRUM_BAND_COUNT, &bands, sizeof(bands));
    const int32_t start = get_in_int(b, 0, 0), end = get_in_int(b, 1, 44100);
    if (start >= end) {
        return NMO_ENGINE_BR_OK;
    }
    if (bands < 0) {
        bands = 0;
    }
    const eng_wave_t *wave = eng_wave(b->engine, sound->file);
    int32_t tick = 0;
    nmo_engine_block_get_local_value(b, SPECTRUM_TICK, &tick, sizeof(tick));
    /* CKTimeManager::GetMainTickCount: PreProcess counts the frame before the behaviors run */
    const int32_t now = (int32_t)(b->engine->frame + 1u);
    if (now != tick) {
        nmo_engine_block_set_local_value(b, SPECTRUM_TICK, &now, sizeof(now));
        const uint16_t channels = wave != NULL ? wave->channels : 0;
        const uint32_t sample_bytes = wave != NULL ? wave->bits_per_sample / 8u : 0;
        if ((channels == 1 || channels == 2) && sample_bytes > 0 && wave->size > 0 && bands > 0) {
            /* CKWaveSound::Lock at the play position, the rest from the buffer's start */
            const size_t lock = (size_t)bands * channels * sample_bytes;
            const size_t align = wave->block_align > 0 ? wave->block_align : sample_bytes * channels;
            size_t cursor = (size_t)((double)sound->position * wave->bytes_per_second / 1000.0);
            cursor = (cursor - cursor % align) % wave->size;
            const size_t taken = lock < wave->size ? lock : wave->size;
            const uint32_t samples = (uint32_t)(taken / sample_bytes);
            const uint32_t frames = channels == 2 ? samples / 2u : samples;
            int8_t *split = (int8_t *)calloc((size_t)samples + 1u, 1u);
            uint8_t *levels = (uint8_t *)calloc((size_t)bands, 1u);
            if (split != NULL && levels != NULL) {
                for (uint32_t i = 0; i < samples; i++) {
                    const size_t at = (cursor + (size_t)i * sample_bytes) % wave->size;
                    const int8_t value = spectrum_sample(wave->data + at, wave->bits_per_sample);
                    /* Two channels apart: the left ones, then the right ones */
                    split[channels == 2 ? (i & 1u) * frames + i / 2u : i] = value;
                }
                if (channels == 1) {
                    spectrum_channel(split, frames, levels, (uint32_t)bands);
                    nmo_engine_block_set_local_value(b, SPECTRUM_BANDS, levels, (size_t)bands);
                } else {
                    uint8_t *right = (uint8_t *)calloc((size_t)bands, 1u);
                    if (right != NULL) {
                        spectrum_channel(split, frames, levels, (uint32_t)bands);
                        spectrum_channel(split + frames, frames, right, (uint32_t)bands);
                        for (int32_t i = 0; i < bands; i++) {
                            levels[i] = (uint8_t)((levels[i] + right[i]) >> 1);
                        }
                        nmo_engine_block_set_local_value(b, SPECTRUM_BANDS, levels, (size_t)bands);
                    }
                    free(right);
                }
            }
            free(split);
            free(levels);
        }
    }
    uint8_t *levels = (uint8_t *)calloc((size_t)bands + 1u, 1u);
    if (levels == NULL) {
        return NMO_ENGINE_BR_OK;
    }
    if (bands > 0) {
        nmo_engine_block_get_local_value(b, SPECTRUM_BANDS, levels, (size_t)bands);
    }
    const double band = wave != NULL ? (double)wave->sample_rate * 0.5 : 0.0;
    const int32_t first = (int32_t)(int64_t)((double)start * bands / band);
    int32_t last = (int32_t)(int64_t)((double)end * bands / band);
    if (first == last) {
        last = first + 1;
    }
    const int32_t stop = last < bands ? last : bands;
    float sum = 0.0f;
    for (int32_t i = first; i < stop; i++) {
        if (i >= 0) {
            sum = (float)((double)levels[i] * 0.0039215689 + sum);
        }
    }
    free(levels);
    const float value = (float)(sum / (double)(last - first));
    nmo_engine_block_set_output_value(b, 0, &value, sizeof(value));
    return NMO_ENGINE_BR_OK;
}

static const nmo_engine_block_desc_t eng_sound_spectrum_blocks[] = {
    {NMO_GUID_INIT(0x47082a75, 0x112b7c1b), "Get Sound Spectrum", bb_get_sound_spectrum, NULL, NULL},
};

nmo_status_t eng_register_sound_spectrum(nmo_engine_t *engine)
{
    return ENG_REGISTER_BLOCKS(engine, eng_sound_spectrum_blocks);
}
