static nmo_status_t nmo_parse_rect(
    void *value,
    const nmo_type_registry_t *registry,
    const char *string)
{
    (void)registry;
    if (!value || !string) {
        NMO_RETURN_ERROR(NMO_ERR_INVALID_ARGUMENT, NMO_SEVERITY_ERROR, "Invalid arguments for rect parse");
    }

    float out[4] = {0};
    nmo_status_t st = parse_float_tuple("Rect", string, out, 4);
    if (st != NMO_OK) {
        char tail = '\0';
        int matched = sscanf(
            string, " ( %f , %f ) , ( %f , %f ) %c",
            &out[0], &out[1], &out[2], &out[3], &tail);
        if (matched == 4) {
            st = NMO_OK;
        }
    }
    if (st != NMO_OK) return st;

    nmo_rect_t *r = (nmo_rect_t *)value;
    r->left = out[0];
    r->top = out[1];
    r->right = out[2];
    r->bottom = out[3];
    NMO_RETURN_OK();
}

static const char *find_matching_paren_end(const char *text)
{
    int depth = 0;
    for (const char *p = text; *p != '\0'; ++p) {
        if (*p == '(') {
            depth++;
        } else if (*p == ')') {
            depth--;
            if (depth == 0) {
                return p + 1;
            }
        }
    }
    return NULL;
}

static nmo_status_t parse_vector_segment(
    const char *start,
    const char *end,
    nmo_vector_t *out_value)
{
    if (!start || !end || end <= start || !out_value) {
        NMO_RETURN_ERROR(NMO_ERR_INVALID_ARGUMENT, NMO_SEVERITY_ERROR,
                         "Invalid vector segment");
    }

    size_t len = (size_t)(end - start);
    char stack_buf[128];
    char *buf = stack_buf;
    if (len + 1u > sizeof(stack_buf)) {
        buf = (char *)malloc(len + 1u);
        if (!buf) {
            NMO_RETURN_ERROR(NMO_ERR_NOMEM, NMO_SEVERITY_ERROR,
                             "Failed to allocate vector segment");
        }
    }

    memcpy(buf, start, len);
    buf[len] = '\0';
    nmo_status_t st = nmo_type_vector3_from_string(out_value, buf);
    if (buf != stack_buf) {
        free(buf);
    }
    return st;
}

static nmo_status_t nmo_parse_box(
    void *value,
    const nmo_type_registry_t *registry,
    const char *string)
{
    (void)registry;
    if (!value || !string) {
        NMO_RETURN_ERROR(NMO_ERR_INVALID_ARGUMENT, NMO_SEVERITY_ERROR, "Invalid arguments for box parse");
    }

    /* Format: ((x,y,z), (x,y,z)) with optional whitespace */
    while (*string && isspace((unsigned char)*string)) string++;
    if (*string != '(') {
        NMO_RETURN_ERROR(NMO_ERR_INVALID_FORMAT, NMO_SEVERITY_ERROR, "Box must start with '('");
    }
    string++;
    while (*string && isspace((unsigned char)*string)) string++;
    if (*string != '(') {
        NMO_RETURN_ERROR(NMO_ERR_INVALID_FORMAT, NMO_SEVERITY_ERROR, "Box must contain '(min, max)'");
    }

    /* Parse first vector3 */
    nmo_vector_t minv = {0};
    const char *p = find_matching_paren_end(string);
    if (!p) {
        NMO_RETURN_ERROR(NMO_ERR_INVALID_FORMAT, NMO_SEVERITY_ERROR, "Unclosed min vector");
    }
    NMO_RETURN_IF_ERROR(parse_vector_segment(string, p, &minv));

    while (*p && isspace((unsigned char)*p)) p++;
    if (*p != ',') {
        NMO_RETURN_ERROR(NMO_ERR_INVALID_FORMAT, NMO_SEVERITY_ERROR, "Box vectors must be separated by ','");
    }
    p++;
    while (*p && isspace((unsigned char)*p)) p++;
    if (*p != '(') {
        NMO_RETURN_ERROR(NMO_ERR_INVALID_FORMAT, NMO_SEVERITY_ERROR, "Box max vector must start with '('");
    }

    nmo_vector_t maxv = {0};
    const char *q = find_matching_paren_end(p);
    if (!q) {
        NMO_RETURN_ERROR(NMO_ERR_INVALID_FORMAT, NMO_SEVERITY_ERROR, "Unclosed max vector");
    }
    NMO_RETURN_IF_ERROR(parse_vector_segment(p, q, &maxv));

    while (*q && isspace((unsigned char)*q)) q++;
    if (*q != ')') {
        NMO_RETURN_ERROR(NMO_ERR_INVALID_FORMAT, NMO_SEVERITY_ERROR, "Box must end with ')'");
    }

    nmo_box_t *b = (nmo_box_t *)value;
    b->min = minv;
    b->max = maxv;
    NMO_RETURN_OK();
}

